    private void CargarDatos() throws FileNotFoundException, IOException{
         tabla.setRowCount(0);
         Id = 0;
          BufferedReader leer = new BufferedReader(new FileReader("nombre.txt"));
       String renglon;
        while((renglon = leer.readLine()) != null){
            Id++;
            //System.out.println("Datos: "+ renglon);
            String []dato = renglon.split(" _ ");  
            tabla.addRow(new Object[]{Id,dato[0],dato[1],dato[2]});
            datos.setModel(tabla);
            
        
        } 
        
        leer.close();
        
    }

