    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        String n = txtNombre.getText();
        String e = txtEdad.getText();
        String t = txttelefono.getText();
        
        if(n.isEmpty()|| e.isEmpty() ||  t.isEmpty()){
            JOptionPane.showMessageDialog(null,"Favor de ingresar todo lo que se pide");
        }else{         
            try {
                FileWriter archivo = new FileWriter("nombre.txt",true);
                archivo.write(n+" _ "+e+" _ "+t+"\n");
                archivo.close();
                JOptionPane.showMessageDialog(null, "Los datos fueron guardados ");
                BorrarCajas();
                CargarDatos();
                
            } catch (IOException ex) {
                Logger.getLogger(Ventanass.class.getName()).log(Level.SEVERE, null, ex);
            }
            
            
        }
       
        
    }//GEN-LAST:event_btnAgregarActionPerformed
